-- Table reservations, ported from the RTR Spring backend.
-- The Node backend reads and writes these tables with the service-role key.
-- Guests never query them directly; admins may read them through RLS.

CREATE TABLE IF NOT EXISTS public.restaurant_tables (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_number text NOT NULL CHECK (char_length(table_number) BETWEEN 1 AND 32),
  area text NOT NULL CHECK (area IN ('TERRACE', 'ROMA', 'VERONA', 'SORRENTO')),
  capacity integer NOT NULL CHECK (capacity BETWEEN 1 AND 50),
  -- HOLD and RESERVED are derived from bookings and are never stored.
  status text NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'MAINTENANCE')),
  x double precision NOT NULL DEFAULT 0,
  y double precision NOT NULL DEFAULT 0,
  width double precision NOT NULL DEFAULT 96,
  height double precision NOT NULL DEFAULT 72,
  rotation double precision NOT NULL DEFAULT 0,
  shape text NOT NULL DEFAULT 'RECTANGLE' CHECK (shape IN ('RECTANGLE', 'CIRCLE')),
  image_url text,
  area_image_url text,
  description text CHECK (char_length(description) <= 500),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS restaurant_tables_active_number_key
  ON public.restaurant_tables (area, lower(table_number)) WHERE active;

CREATE TABLE IF NOT EXISTS public.bookings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_code text NOT NULL UNIQUE CHECK (char_length(booking_code) <= 32),
  customer_name text NOT NULL CHECK (char_length(customer_name) BETWEEN 1 AND 120),
  customer_phone text NOT NULL CHECK (char_length(customer_phone) BETWEEN 1 AND 32),
  customer_email text NOT NULL CHECK (char_length(customer_email) BETWEEN 3 AND 160),
  booking_date date NOT NULL,
  start_time time NOT NULL,
  end_time time NOT NULL,
  number_of_guests integer NOT NULL CHECK (number_of_guests BETWEEN 1 AND 200),
  area text NOT NULL CHECK (area IN ('TERRACE', 'ROMA', 'VERONA', 'SORRENTO')),
  note text CHECK (char_length(note) <= 1000),
  rejection_reason text CHECK (char_length(rejection_reason) <= 1000),
  status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'COMPLETED')),
  -- Pending requests are listed first in the admin inbox.
  pending_rank smallint GENERATED ALWAYS AS (CASE WHEN status = 'PENDING' THEN 0 ELSE 1 END) STORED,
  email_verified boolean NOT NULL DEFAULT false,
  verification_id uuid UNIQUE,
  otp_hash text,
  otp_expires_at timestamptz,
  otp_attempt_count integer NOT NULL DEFAULT 0,
  otp_resend_count integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  approved_at timestamptz,
  rejected_at timestamptz,
  CONSTRAINT bookings_time_range CHECK (end_time > start_time)
);
CREATE INDEX IF NOT EXISTS bookings_date_status_idx ON public.bookings (booking_date, status);
CREATE INDEX IF NOT EXISTS bookings_inbox_idx ON public.bookings (email_verified, pending_rank, created_at DESC);
CREATE INDEX IF NOT EXISTS bookings_email_date_idx ON public.bookings (lower(customer_email), booking_date);

CREATE TABLE IF NOT EXISTS public.booking_tables (
  booking_id bigint NOT NULL REFERENCES public.bookings(id) ON DELETE CASCADE,
  table_id bigint NOT NULL REFERENCES public.restaurant_tables(id) ON DELETE RESTRICT,
  PRIMARY KEY (booking_id, table_id)
);
CREATE INDEX IF NOT EXISTS booking_tables_table_idx ON public.booking_tables (table_id);

CREATE OR REPLACE FUNCTION public.reservations_touch_updated_at()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS restaurant_tables_touch ON public.restaurant_tables;
CREATE TRIGGER restaurant_tables_touch BEFORE UPDATE ON public.restaurant_tables
  FOR EACH ROW EXECUTE FUNCTION public.reservations_touch_updated_at();
DROP TRIGGER IF EXISTS bookings_touch ON public.bookings;
CREATE TRIGGER bookings_touch BEFORE UPDATE ON public.bookings
  FOR EACH ROW EXECUTE FUNCTION public.reservations_touch_updated_at();

ALTER TABLE public.restaurant_tables ENABLE ROW LEVEL SECURITY;
