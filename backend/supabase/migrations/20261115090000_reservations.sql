ALTER TABLE public.booking_tables ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.restaurant_tables, public.bookings, public.booking_tables FROM anon;
GRANT SELECT ON public.restaurant_tables, public.bookings, public.booking_tables TO authenticated;
DROP POLICY IF EXISTS "Admins can read restaurant tables" ON public.restaurant_tables;
CREATE POLICY "Admins can read restaurant tables" ON public.restaurant_tables
  FOR SELECT TO authenticated USING (public.has_role(auth.uid(), 'admin'));
DROP POLICY IF EXISTS "Admins can read bookings" ON public.bookings;
CREATE POLICY "Admins can read bookings" ON public.bookings
  FOR SELECT TO authenticated USING (public.has_role(auth.uid(), 'admin'));
DROP POLICY IF EXISTS "Admins can read booking tables" ON public.booking_tables;
CREATE POLICY "Admins can read booking tables" ON public.booking_tables
  FOR SELECT TO authenticated USING (public.has_role(auth.uid(), 'admin'));

-- A table is blocked for the whole day by any pending or approved booking,
-- matching the RTR rules. Unverified requests whose OTP expired do not block.
CREATE OR REPLACE FUNCTION public.booking_assert_available(
  p_booking_id bigint, p_date date, p_table_ids bigint[], p_email text, p_check_tables boolean, p_check_email boolean)
RETURNS void LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  -- Serialise all writes for one date so two guests cannot claim the same table.
  PERFORM pg_advisory_xact_lock(hashtext('rtr-booking:' || p_date::text));
  IF p_check_tables AND EXISTS (
    SELECT 1 FROM public.bookings b JOIN public.booking_tables bt ON bt.booking_id = b.id
    WHERE bt.table_id = ANY (p_table_ids)
      AND b.booking_date = p_date
      AND b.status IN ('PENDING', 'APPROVED')
      AND b.id IS DISTINCT FROM p_booking_id
      AND (b.email_verified OR b.otp_expires_at > now())
  ) THEN
    RAISE EXCEPTION 'TABLE_NOT_AVAILABLE: The selected table is no longer available.';
  END IF;
  IF p_check_email AND EXISTS (
    SELECT 1 FROM public.bookings b
    WHERE lower(b.customer_email) = lower(trim(p_email))
      AND b.booking_date = p_date
      AND b.email_verified
      AND b.id IS DISTINCT FROM p_booking_id
  ) THEN
    RAISE EXCEPTION 'EMAIL_ALREADY_BOOKED_TODAY: This email already has a booking on the selected date.';
  END IF;
END;
$$;

-- Creates (p_id NULL) or updates a booking and replaces its tables atomically.
CREATE OR REPLACE FUNCTION public.booking_save(
  p_id bigint, p_data jsonb, p_table_ids bigint[], p_check_tables boolean, p_check_email boolean)
RETURNS bigint LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
  v_id bigint := p_id;
BEGIN
  PERFORM public.booking_assert_available(p_id, (p_data->>'booking_date')::date, p_table_ids,
    p_data->>'customer_email', p_check_tables, p_check_email);
  IF v_id IS NULL THEN
    INSERT INTO public.bookings (booking_code, customer_name, customer_phone, customer_email, booking_date,
      start_time, end_time, number_of_guests, area, note, status, email_verified, verification_id, otp_hash, otp_expires_at)
    VALUES (p_data->>'booking_code', p_data->>'customer_name', p_data->>'customer_phone', p_data->>'customer_email',
      (p_data->>'booking_date')::date, (p_data->>'start_time')::time, (p_data->>'end_time')::time,
      (p_data->>'number_of_guests')::int, p_data->>'area', p_data->>'note', p_data->>'status',
      COALESCE((p_data->>'email_verified')::boolean, false), (p_data->>'verification_id')::uuid,
      p_data->>'otp_hash', (p_data->>'otp_expires_at')::timestamptz)
    RETURNING id INTO v_id;
  ELSE
    UPDATE public.bookings SET
      customer_name = p_data->>'customer_name', customer_phone = p_data->>'customer_phone',
      customer_email = p_data->>'customer_email', booking_date = (p_data->>'booking_date')::date,
      start_time = (p_data->>'start_time')::time, end_time = (p_data->>'end_time')::time,
      number_of_guests = (p_data->>'number_of_guests')::int, area = p_data->>'area', note = p_data->>'note',
      status = COALESCE(p_data->>'status', status)
    WHERE id = v_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'BOOKING_NOT_FOUND: Booking not found.'; END IF;
    DELETE FROM public.booking_tables WHERE booking_id = v_id;
  END IF;
  INSERT INTO public.booking_tables (booking_id, table_id) SELECT v_id, unnest(p_table_ids);
  RETURN v_id;
END;
$$;

-- Applies a status change after re-checking table and email availability.
CREATE OR REPLACE FUNCTION public.booking_transition(
  p_id bigint, p_data jsonb, p_check_tables boolean, p_check_email boolean)
RETURNS void LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
  v public.bookings;
BEGIN
  SELECT * INTO v FROM public.bookings WHERE id = p_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'BOOKING_NOT_FOUND: Booking not found.'; END IF;
  PERFORM public.booking_assert_available(p_id, v.booking_date,
    ARRAY(SELECT table_id FROM public.booking_tables WHERE booking_id = p_id),
    v.customer_email, p_check_tables, p_check_email);
  UPDATE public.bookings SET
    status = COALESCE(p_data->>'status', status),
    email_verified = COALESCE((p_data->>'email_verified')::boolean, email_verified),
    otp_hash = CASE WHEN p_data ? 'otp_hash' THEN p_data->>'otp_hash' ELSE otp_hash END,
    approved_at = CASE WHEN p_data ? 'approved_at' THEN (p_data->>'approved_at')::timestamptz ELSE approved_at END
  WHERE id = p_id;
END;
$$;

REVOKE ALL ON FUNCTION public.booking_assert_available(bigint, date, bigint[], text, boolean, boolean) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.booking_save(bigint, jsonb, bigint[], boolean, boolean) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.booking_transition(bigint, jsonb, boolean, boolean) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.booking_assert_available(bigint, date, bigint[], text, boolean, boolean) TO service_role;
GRANT EXECUTE ON FUNCTION public.booking_save(bigint, jsonb, bigint[], boolean, boolean) TO service_role;
GRANT EXECUTE ON FUNCTION public.booking_transition(bigint, jsonb, boolean, boolean) TO service_role;

-- Seed the RTR floor: Terrace T1-T12, Roma R1-R12, Verona V1-V16, Sorrento S1-S6.
INSERT INTO public.restaurant_tables (table_number, area, capacity, x, y, width, height, shape, description)
SELECT prefix || n, area, 2,
  -- Two rows per area, spaced to stay inside the 1000px-wide admin floor plan.
  80 + ((n - 1) % ceil(total / 2.0)::int) * least(150, floor(800.0 / greatest(ceil(total / 2.0) - 1, 1))),
  CASE WHEN n <= ceil(total / 2.0) THEN 90 ELSE 270 END,
  CASE WHEN n % 3 = 0 THEN 112 ELSE 96 END,
  CASE WHEN n % 3 = 0 THEN 84 ELSE 72 END,
  CASE WHEN n % 4 = 0 THEN 'CIRCLE' ELSE 'RECTANGLE' END,
  area || ' table for 2 guests.'
FROM (VALUES ('TERRACE', 'T', 12), ('ROMA', 'R', 12), ('VERONA', 'V', 16), ('SORRENTO', 'S', 6)) AS a(area, prefix, total)
CROSS JOIN LATERAL generate_series(1, total) AS n
WHERE NOT EXISTS (SELECT 1 FROM public.restaurant_tables);
